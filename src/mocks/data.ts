export function buildStages(deals: Deal[]): Stage[] {
  return stageMeta.map((stage) => {
    const stageDeals = deals.filter((deal) => deal.stageId === stage.id);
    const valueSum = stageDeals.reduce((sum, deal) => sum + deal.value, 0);
    return {
      ...stage,
      dealCount: stageDeals.length,
      valueSum,
    };
  });
}

export function createPipeline(): PipelineData {
  return {
    stages: buildStages(baseDeals),
    deals: baseDeals,
  };
}

